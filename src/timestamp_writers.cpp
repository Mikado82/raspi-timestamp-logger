#include "timestamp_writers.hpp"

#include <iostream>

#include <boost/mysql/with_params.hpp>
#include <boost/mysql/results.hpp>
#include <boost/mysql/error_with_diagnostics.hpp>

using namespace std;

file_writer::file_writer(const string &filename)
{
    // Enable exceptions
    file.exceptions(ifstream::failbit | ifstream::badbit);

    // Open file for writing in append mode
    file.open(filename, ios::out | ios::app);
}

void file_writer::operator()(const string &timestamp)
{
    // Write the timestamp the output file
    file << timestamp << "\n";
    
    // Output success info
    cout << "Successfully appended output file\n";
}

void file_writer::handle_exception(exception_ptr ex_ptr)
{
    try
    {
        // Rethrow the exception to handle it
        if(ex_ptr) rethrow_exception(ex_ptr);
    }
    // Catch I/O exceptions
    catch(const ifstream::failure& e)
    {
        // Display error message
        cerr << "FILE WRITER ERROR: " << e.what() << '\n';
    }
}

db_writer::db_writer(
    const boost::mysql::connect_params &params,
    const string_view table_name)
    : conn(ctx), table_name(table_name)
{
    // Connect to the database
    params.auth_plugin_name = "mysql_native_password";
    conn.connect(params);
}

void db_writer::operator()(const string &timestamp)
{
    // Insert the timestamp into the database
    boost::mysql::results result;
    conn.execute(
        boost::mysql::with_params(
            "INSERT INTO " + std::string(table_name) + " (start_time) VALUES ({})",
            timestamp
        ),
        result
    );

    // results::last_insert_id retrieves the value of the latest
    // AUTO_INCREMENT field generated by the executed query, if any.
    auto id = result.last_insert_id();

    // Output success info with created ID
    cout << "Successfully created DB entry with ID: " << id << "\n";
}

void db_writer::handle_exception(exception_ptr ex_ptr)
{
    try
    {
        // Rethrow the exception to handle it
        if(ex_ptr) rethrow_exception(ex_ptr);
    }
    // Catch boost::mysql exceptions
    catch (const boost::mysql::error_with_diagnostics& e)
    {
        // Display error message
        cerr << "DATABASE WRITER ERROR: " << e.what() << '\n';
        auto server_msg = e.get_diagnostics().server_message();
        if(!server_msg.empty())
            cerr << "Server diagnostics: " << server_msg << endl;
    }
}
